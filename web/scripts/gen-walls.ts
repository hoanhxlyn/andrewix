/**
 * Regenerates `src/routes/Walls/walls.ts` from the wallpaper flake inputs of the repository, so the
 * deployed gallery links to the exact revisions the hosts use. Run after the inputs change:
 *
 *   bun run walls
 *
 * Paths come from the inputs nix already has in the store, so this works offline and needs no
 * GitHub API. Images stay on GitHub: only their paths are baked here, and the browser fetches each
 * one lazily.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/** Flake inputs holding wallpapers, keyed by the source name the gallery shows. */
const SOURCES = {
  catppuccin: "walls-catppuccin-mocha",
  gruvbox: "gruvbox-wallpapers",
  tokyonight: "tokyonight-wallpapers",
} as const;

const IMAGE = /\.(png|jpe?g|webp)$/i;
const OUT = new URL("../src/data/walls.ts", import.meta.url);
const LOCK = new URL("../../flake.lock", import.meta.url);

interface Locked {
  owner: string;
  repo: string;
  rev: string;
}

interface Wall {
  source: string;
  path: string;
  url: string;
}

/** Store path of a locked input, fetching it only if no build has it yet. */
function storePath({ owner, repo, rev }: Locked): string {
  const stdout = execFileSync(
    "nix",
    ["flake", "metadata", "--json", `github:${owner}/${repo}/${rev}`],
    { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  );
  return (JSON.parse(stdout) as { path: string }).path;
}

function imagesOf(source: string, name: string): Wall[] {
  const { nodes } = JSON.parse(readFileSync(LOCK, "utf8")) as {
    nodes: Record<string, { locked: Locked }>;
  };
  const locked = nodes[name]?.locked;
  if (locked === undefined) throw new Error(`flake.lock has no input ${name}`);
  const { owner, repo, rev } = locked;
  const root = storePath({ owner, repo, rev });
  const base = `https://raw.githubusercontent.com/${owner}/${repo}/${rev}`;

  return readdirSync(root, { recursive: true })
    .map(String)
    .filter((path) => IMAGE.test(path))
    .map((path) => ({
      source,
      path,
      url: `${base}/${path.split(/[/\\]/).map(encodeURIComponent).join("/")}`,
    }));
}

const walls = Object.entries(SOURCES)
  .flatMap(([source, name]) => imagesOf(source, name))
  .sort(
    (a, b) =>
      a.source.localeCompare(b.source) ||
      a.path.localeCompare(b.path, "en", { numeric: true }),
  );

/**
 * The generated file in the format `biome check` expects: unquoted keys, trailing commas.
 */
function literal({ source, path, url }: Wall): string {
  return [
    "  {",
    `    source: ${JSON.stringify(source)},`,
    `    path: ${JSON.stringify(path)},`,
    `    url: ${JSON.stringify(url)},`,
    "  },",
  ].join("\n");
}

const file = `// Generated by scripts/gen-walls.ts from the wallpaper flake inputs. Do not edit.
// Regenerate with: bun run walls

/** One image of a wallpaper source, with the URL it is fetched from. */
export interface Wall {
  source: string;
  path: string;
  url: string;
}

/** Every wallpaper of the sources the hosts can use. */
export const walls: readonly Wall[] = [
${walls.map(literal).join("\n")}
];
`;

mkdirSync(dirname(OUT.pathname), { recursive: true });
writeFileSync(OUT, file);
console.log(`${walls.length} wallpapers written to ${OUT.pathname}`);
